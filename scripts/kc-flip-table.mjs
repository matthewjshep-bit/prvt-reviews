// kc-flip-table.mjs — King County's flip ratios as a small module the broker can import.
//
// scripts/kc-flips.mjs reads ~170 MB of county files into ghl-broker/tmp/kc-flips.json, which is
// gitignored and never on Render. The pricing engine only needs the ratio table: per ZIP, how many
// flips were resold in the window and what share of the resale the flipper paid. This writes that,
// counts and quantiles only (no names, no parcels, no addresses), to shared/kc-flip-ratios.js.
//
//   node scripts/kc-flips.mjs --refresh      # fresh county files → ghl-broker/tmp/kc-flips.json
//   node scripts/kc-flip-table.mjs [path]    # → shared/kc-flip-ratios.js, then sync-shared and commit
//
// Refresh by hand every month or two; the engine reads `asOf` and says how old the table is.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const src = process.argv[2] || path.join(root, "ghl-broker", "tmp", "kc-flips.json");
if (!fs.existsSync(src)) { console.error(`no ${src} — run scripts/kc-flips.mjs first`); process.exit(1); }
const { asOf, table } = JSON.parse(fs.readFileSync(src, "utf8"));
const zips = Object.fromEntries(Object.entries(table.zips || {}).filter(([, s]) => s.n >= 1).sort(([a], [b]) => a.localeCompare(b)));
const body = `// kc-flip-ratios.js — GENERATED by scripts/kc-flip-table.mjs from King County's recorded sales.
// What share of the resale price a flipper paid for the house as-is, per ZIP and county-wide, from
// flips resold in the ${table.windowMonths} months before ${asOf}. Counts and quantiles only. Do not edit by hand.

export const KC_FLIP_RATIOS = ${JSON.stringify({ asOf, windowMonths: table.windowMonths, county: table.county, zips }, null, 1)};
`;
fs.writeFileSync(path.join(root, "shared", "kc-flip-ratios.js"), body);
console.log(`shared/kc-flip-ratios.js: as of ${asOf}, ${Object.keys(zips).length} ZIPs, county n ${table.county.n} median ${table.county.median}`);
